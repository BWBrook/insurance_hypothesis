"""End-to-end runner for the insurance hypothesis simulations and figures.

Default behaviour (no flags):
- Uses production outputs under data/sim/production/ when available.
- Falls back to existing simulation outputs under data/sim/grid/ (run1, pos_full, phi0/07/09/095_reduced).
- Regenerates summary tables and figures into analysis/reports/.
- Copies key panels into paper/manuscript/figures/.

Optional: rerun legacy exploratory fallback grids with `--rerun-data`. Final
production grids are generated by versioned specs under analysis/production_specs/.
"""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path

import pandas as pd

from insurance_sim.diagnostics import (
    select_variance_decomposition_rows,
    summarize_fig4_partial_association,
    summarize_variance_decomposition,
)
from insurance_sim.figures import (
    ensure_reports,
    make_cv_vs_synchrony,
    make_panel,
    make_phi_overlay,
    make_positive_matched_control,
    make_richness_scaling,
    make_species_cv_diagnostic,
    make_synchrony_panels,
)
from insurance_sim.reporting import (
    DEFAULT_DATA_RUNS,
    copy_existing_files,
    load_summary,
    remove_existing_files,
    summarize_numerical_guard_csv,
    validate_phi_run_lengths,
    write_guard_summary_markdown,
)
from insurance_sim.production_figures import (
    write_production_fig1,
    write_production_fig2_richness,
    write_production_fig3_synchrony,
    write_production_fig4_cv_synchrony,
    write_production_fig5_persistence,
    write_production_figs3_positive_matched_control,
    write_production_mixed_heatmap_supplement,
    write_production_species_cv_supplement,
)

REPORTS = Path("analysis/reports")
FIG_DIR = Path("paper/manuscript/figures")
DATA_RUNS = DEFAULT_DATA_RUNS
FIG1_PRODUCTION_CORE = Path("data/sim/production/fig1_s4_highres_v1/summaries.parquet")
FIG1_PRODUCTION_HIGHSIGMA = Path("data/sim/production/fig1_s4_highsigma_v1/summaries.parquet")
FIG2_PRODUCTION_RICHNESS = Path("data/sim/production/fig2_richness_mixed_v1/summaries.parquet")
FIG3_PRODUCTION_SYNCHRONY = Path("data/sim/production/fig3_synchrony_v1/summaries.parquet")
FIGS3_PRODUCTION_POS_MATCHED = Path("data/sim/production/figs3_positive_matched_control_v1/summaries.parquet")
FIG5_PRODUCTION_PERSISTENCE = Path("data/sim/production/fig5_persistence_mixed_v1/summaries.parquet")


def _load_optional_summary(run_name: str) -> pd.DataFrame | None:
    """Load an exploratory cached summary if present, otherwise defer to production paths."""
    spec = DATA_RUNS[run_name]
    if not spec.path.exists():
        print(f"Skipping cached grid {run_name}; missing {spec.path}")
        return None
    return load_summary(spec.path)


def _require_summary(summary: pd.DataFrame | None, run_name: str, purpose: str) -> pd.DataFrame:
    """Return a cached summary or raise a targeted fallback error."""
    if summary is not None:
        return summary
    path = DATA_RUNS[run_name].path
    raise FileNotFoundError(
        f"Missing cached grid required for {purpose}: {path}. "
        "Retrieve cached data, run with --rerun-data, or provide the relevant production summary."
    )


def _require_phi_runs(phi_runs: dict[str, pd.DataFrame], purpose: str) -> dict[str, pd.DataFrame]:
    """Require all cached phi-sensitivity runs for the legacy Figure 5 fallback."""
    expected = [key for key in DATA_RUNS if key.startswith("phi")]
    missing = [str(DATA_RUNS[key].path) for key in expected if key not in phi_runs]
    if missing:
        raise FileNotFoundError(
            f"Missing cached phi-sensitivity grid(s) required for {purpose}: "
            + ", ".join(missing)
            + ". Retrieve cached data, run with --rerun-data, or provide the Figure 5 production summary."
        )
    return phi_runs


def run_command(cmd: list[str]) -> None:
    print("Running:", " ".join(cmd))
    subprocess.run(cmd, check=True)


def rerun_data() -> None:
    for name, spec in DATA_RUNS.items():
        args = ["python", "analysis/run_full_grid.py", "--run-name", name, *spec.args]
        run_command(["uv", "run"] + args)


def summarize_numerical_guards() -> None:
    """Run and summarise numerical-guard diagnostics for manuscript transparency."""
    REPORTS.mkdir(parents=True, exist_ok=True)
    run_command(["uv", "run", "python", "analysis/check_numerical_guards.py"])

    in_path = REPORTS / "numerical_guard_rates.csv"
    if not in_path.exists():
        print(f"Warning: missing expected guard diagnostics file: {in_path}")
        return

    summary = summarize_numerical_guard_csv(in_path)
    out_csv = REPORTS / "numerical_guard_rates_summary.csv"
    summary.to_csv(out_csv, index=False)
    write_guard_summary_markdown(summary, REPORTS / "numerical_guard_rates_summary.md")


def summarize_production_diagnostics(production_path: Path) -> None:
    """Write manuscript diagnostics derived from existing production summaries."""
    df = pd.read_parquet(production_path)
    variance = summarize_variance_decomposition(df)
    variance.to_csv(REPORTS / "variance_decomposition_fig2_mixed_summary.csv", index=False)
    select_variance_decomposition_rows(variance).to_csv(
        REPORTS / "variance_decomposition_fig2_mixed_selected_summary.csv",
        index=False,
    )
    summarize_fig4_partial_association(df).to_csv(
        REPORTS / "fig4_partial_association_summary.csv",
        index=False,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Run simulations and regenerate figures")
    parser.add_argument("--rerun-data", action="store_true", help="Rerun simulations instead of using cached parquet files")
    parser.add_argument(
        "--skip-guard-audit",
        action="store_true",
        help="Skip numerical-guard diagnostics refresh (enabled by default).",
    )
    args = parser.parse_args()

    if args.rerun_data:
        rerun_data()

    if not args.skip_guard_audit:
        summarize_numerical_guards()

    # Load cached exploratory summaries only when available. Production-backed
    # figures below do not need these untracked grid files.
    summary_mixed = _load_optional_summary("run1")
    summary_pos = _load_optional_summary("pos_full")
    summary_pos_matched = _load_optional_summary("pos_matched")
    phi_runs = {
        key: load_summary(spec.path)
        for key, spec in DATA_RUNS.items()
        if key.startswith("phi") and spec.path.exists()
    }
    if phi_runs:
        validate_phi_run_lengths(phi_runs)

    # Per-run summary figs
    if summary_mixed is not None:
        ensure_reports(summary_mixed, REPORTS / "run1")
    if summary_pos is not None:
        ensure_reports(summary_pos, REPORTS / "pos_full")
    if summary_pos_matched is not None:
        ensure_reports(summary_pos_matched, REPORTS / "pos_matched")
    for key, df in phi_runs.items():
        ensure_reports(df, REPORTS / key)

    # Panels
    panel_path = REPORTS / "fig1_panels.png"
    panel_pdf_path = panel_path.with_suffix(".pdf")
    if FIG1_PRODUCTION_CORE.exists() and FIG1_PRODUCTION_HIGHSIGMA.exists():
        write_production_fig1(
            core_path=FIG1_PRODUCTION_CORE,
            highsigma_path=FIG1_PRODUCTION_HIGHSIGMA,
            out_png=panel_path,
            out_pdf=panel_pdf_path,
            summary_out=REPORTS / "fig1_panels_summary.csv",
        )
    else:
        make_panel(
            _require_summary(summary_mixed, "run1", "legacy Figure 1 fallback"),
            _require_summary(summary_pos, "pos_full", "legacy Figure 1 fallback"),
            panel_path,
        )

    sync_panel_path = REPORTS / "fig3_imposed_vs_realised_panels.png"
    sync_panel_pdf_path = sync_panel_path.with_suffix(".pdf")
    if FIG3_PRODUCTION_SYNCHRONY.exists():
        write_production_fig3_synchrony(
            production_path=FIG3_PRODUCTION_SYNCHRONY,
            out_png=sync_panel_path,
            out_pdf=sync_panel_pdf_path,
            summary_out=REPORTS / "fig3_imposed_vs_realised_panels_summary.csv",
        )
    else:
        make_synchrony_panels(
            _require_summary(summary_mixed, "run1", "legacy Figure 3 fallback"),
            _require_summary(summary_pos, "pos_full", "legacy Figure 3 fallback"),
            sync_panel_path,
        )

    phi_overlay_path = REPORTS / "fig5_phi_sensitivity_sigma0.5_extended.png"
    phi_overlay_pdf_path = phi_overlay_path.with_suffix(".pdf")
    if FIG5_PRODUCTION_PERSISTENCE.exists():
        write_production_fig5_persistence(
            production_path=FIG5_PRODUCTION_PERSISTENCE,
            out_png=phi_overlay_path,
            out_pdf=phi_overlay_pdf_path,
            summary_out=REPORTS / "fig5_phi_sensitivity_sigma0.5_extended_summary.csv",
        )
    else:
        make_phi_overlay(_require_phi_runs(phi_runs, "legacy Figure 5 fallback"), phi_overlay_path)

    cv_sync_path = REPORTS / "fig4_cv_vs_synchrony_mixed.png"
    cv_sync_pdf_path = cv_sync_path.with_suffix(".pdf")
    if FIG2_PRODUCTION_RICHNESS.exists():
        summarize_production_diagnostics(FIG2_PRODUCTION_RICHNESS)
        write_production_fig4_cv_synchrony(
            production_path=FIG2_PRODUCTION_RICHNESS,
            out_png=cv_sync_path,
            out_pdf=cv_sync_pdf_path,
            summary_out=REPORTS / "fig4_cv_vs_synchrony_mixed_summary.csv",
        )
    else:
        make_cv_vs_synchrony(
            _require_summary(summary_mixed, "run1", "legacy Figure 4 fallback"),
            cv_sync_path,
        )

    # Richness scaling curve (prefer dedicated richness sweep if available)
    richness_path = Path("data/sim/grid/run1_richness/summaries.parquet")
    if richness_path.exists():
        richness_df = pd.read_parquet(richness_path)
    else:
        richness_df = summary_mixed
    richness_fig_path = REPORTS / "fig2_richness_scaling_mixed.png"
    richness_fig_pdf_path = richness_fig_path.with_suffix(".pdf")
    if FIG2_PRODUCTION_RICHNESS.exists():
        write_production_fig2_richness(
            production_path=FIG2_PRODUCTION_RICHNESS,
            out_png=richness_fig_path,
            out_pdf=richness_fig_pdf_path,
            summary_out=REPORTS / "fig2_richness_scaling_mixed_summary.csv",
        )
    else:
        make_richness_scaling(
            _require_summary(richness_df, "run1", "legacy Figure 2 fallback"),
            richness_fig_path,
        )

    species_cv_path = REPORTS / "figS4_production_species_cv_vs_rho.png"
    species_cv_pdf_path = species_cv_path.with_suffix(".pdf")
    if FIG3_PRODUCTION_SYNCHRONY.exists():
        write_production_species_cv_supplement(
            production_path=FIG3_PRODUCTION_SYNCHRONY,
            out_png=species_cv_path,
            out_pdf=species_cv_pdf_path,
            summary_out=REPORTS / "figS4_production_species_cv_vs_rho_summary.csv",
        )
    else:
        make_species_cv_diagnostic(
            _require_summary(summary_mixed, "run1", "legacy Figure S4 fallback"),
            _require_summary(summary_pos, "pos_full", "legacy Figure S4 fallback"),
            species_cv_path,
            summary_out_path=REPORTS / "figS4_production_species_cv_vs_rho_summary.csv",
        )

    # Promote mixed-grid heatmaps to supplementary figure names.
    supp_cv_src = REPORTS / "run1_cv_total.png"
    supp_phi_src = REPORTS / "run1_phi_ldm.png"
    supp_cv_path = REPORTS / "figS1_production_mixed_cv_total.png"
    supp_cv_pdf_path = supp_cv_path.with_suffix(".pdf")
    supp_phi_path = REPORTS / "figS2_production_mixed_phi_ldm.png"
    supp_phi_pdf_path = supp_phi_path.with_suffix(".pdf")
    if FIG2_PRODUCTION_RICHNESS.exists():
        write_production_mixed_heatmap_supplement(
            production_path=FIG2_PRODUCTION_RICHNESS,
            metric="cv_total",
            metric_label=r"Mean $\mathrm{CV}_{\mathrm{tot}}$",
            out_png=supp_cv_path,
            out_pdf=supp_cv_pdf_path,
            summary_out=REPORTS / "figS1_production_mixed_cv_total_summary.csv",
        )
        write_production_mixed_heatmap_supplement(
            production_path=FIG2_PRODUCTION_RICHNESS,
            metric="phi_ldm",
            metric_label=r"Mean $\phi_{\mathrm{LdM}}$",
            out_png=supp_phi_path,
            out_pdf=supp_phi_pdf_path,
            summary_out=REPORTS / "figS2_production_mixed_phi_ldm_summary.csv",
        )
    else:
        if supp_cv_src.exists():
            supp_cv_path.write_bytes(supp_cv_src.read_bytes())
            supp_cv_src.unlink()
        if supp_phi_src.exists():
            supp_phi_path.write_bytes(supp_phi_src.read_bytes())
            supp_phi_src.unlink()

    # Magnitude-matched aligned-slope control (if available)
    matched_path: Path | None = None
    matched_pdf_path: Path | None = None
    if FIGS3_PRODUCTION_POS_MATCHED.exists():
        matched_path = REPORTS / "figS3_positive_matched_control.png"
        matched_pdf_path = matched_path.with_suffix(".pdf")
        write_production_figs3_positive_matched_control(
            production_path=FIGS3_PRODUCTION_POS_MATCHED,
            out_png=matched_path,
            out_pdf=matched_pdf_path,
            summary_out=REPORTS / "figS3_positive_matched_control_summary.csv",
        )
    elif summary_pos_matched is not None:
        matched_path = REPORTS / "figS3_positive_matched_control.png"
        make_positive_matched_control(
            _require_summary(summary_mixed, "run1", "legacy Figure S3 fallback"),
            _require_summary(summary_pos, "pos_full", "legacy Figure S3 fallback"),
            summary_pos_matched,
            matched_path,
        )

    # Copy key panels to paper/manuscript/figures
    figure_paths = [
        panel_path,
        panel_pdf_path,
        sync_panel_path,
        sync_panel_pdf_path,
        cv_sync_path,
        cv_sync_pdf_path,
        phi_overlay_path,
        phi_overlay_pdf_path,
        supp_cv_path,
        supp_cv_pdf_path,
        supp_phi_path,
        supp_phi_pdf_path,
        species_cv_path,
        species_cv_pdf_path,
        richness_fig_path,
        richness_fig_pdf_path,
    ]
    if matched_path is not None:
        figure_paths.append(matched_path)
    if matched_pdf_path is not None:
        figure_paths.append(matched_pdf_path)
    copy_existing_files(figure_paths, FIG_DIR)

    # Remove stale supplementary filenames after transition to figS* names.
    remove_existing_files(
        [
            FIG_DIR / "run1_cv_total.png",
            FIG_DIR / "run1_phi_ldm.png",
            REPORTS / "figS1_run1_cv_total.png",
            REPORTS / "figS2_run1_phi_ldm.png",
            REPORTS / "figS4_species_cv_vs_rho.png",
            REPORTS / "positive_matched_control.png",
            FIG_DIR / "positive_matched_control.png",
        ]
    )

    print("Run complete. Figures in analysis/reports and paper/manuscript/figures.")


if __name__ == "__main__":
    main()
